export const FONT_H = 9;   // cell height incl. descenders
export const CAP_H = 7;
const SPACE = 3, GAP = 1;

const glyphs = {};
for (const [ch, src] of Object.entries(G)) {
  const rows = src.split(' ');
  while (rows.length < FONT_H) rows.push('.'.repeat(rows[0].length));
  glyphs[ch] = { w: rows[0].length, rows };
}

// the parsed glyph table and spacing, for building the menu's web font
export const GLYPHS = glyphs;
export const SPACE_W = SPACE, GLYPH_GAP = GAP;

export function measure(text) {
  let w = 0;
  for (const ch of text) w += (ch === ' ' ? SPACE : (glyphs[ch] || glyphs['?']).w) + GAP;
  return Math.max(0, w - GAP);
}

// Calls plot(x, y) for each lit pixel of `text` at scale `s`, top-left at (x, y).
export function eachPixel(text, x, y, s, plot) {
  let cx = x;
  for (const ch of text) {
    if (ch === ' ') { cx += (SPACE + GAP) * s; continue; }
    const g = glyphs[ch] || glyphs['?'];
    for (let r = 0; r < FONT_H; r++) {
      const row = g.rows[r];
      for (let c = 0; c < g.w; c++) if (row[c] === '#') plot(cx + c * s, y + r * s);
    }
    cx += (g.w + GAP) * s;
  }
}

// Plain text onto a 2D context (fillStyle colour), optional 1px drop shadow.
export function drawText(ctx, text, x, y, color, { scale = 1, shadow = null, outline = null } = {}) {
  const s = scale;
  if (outline) {
    ctx.fillStyle = outline;
    eachPixel(text, x, y, s, (px, py) => ctx.fillRect(px - 1, py - 1, s + 2, s + 2));
  }
  if (shadow) {
    ctx.fillStyle = shadow;
    eachPixel(text, x, y, s, (px, py) => ctx.fillRect(px + 1, py + 1, s, s));
  }
  ctx.fillStyle = color;
  eachPixel(text, x, y, s, (px, py) => ctx.fillRect(px, py, s, s));
}

// Greedy word wrap to a pixel width.
export function wrap(text, maxW) {
  const out = []; let line = '';
  for (const word of text.split(' ')) {
    const t = line ? line + ' ' + word : word;
    if (measure(t) <= maxW || !line) line = t; else { out.push(line); line = word; }
  }
  if (line) out.push(line);
  return out;
}
